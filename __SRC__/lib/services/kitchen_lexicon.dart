  /// 词级纠错表。
  ///
  /// 每一条都要有出处，不许凭语感编。前两条来自 2026-11-15 真机日志里
  /// 同一份字幕的上下行对照（「1勺老迪」/「1河老抽」、「1勺耗油」），
  /// 后两条来自 subtitle_fuse.dart 注释记录的真实错版。
  static const Map<String, String> corrections = <String, String>{
    '老迪': '老抽',
    '耗油': '蚝油',
    '小米鎌': '小米辣',
    '白糠': '白糖',
    '鸡旦': '鸡蛋',
    '豆辨酱': '豆瓣酱',
  };

  /// 全部规范词，按长度降序 —— 长词先命中，避免「青椒」抢在「尖青椒」前面。
  static final List<String> allWords = <String>[
    ...{...ingredients, ...cookTerms},
  ]..sort((a, b) => b.length.compareTo(a.length));

  /// 只给 IngredientScan 用的食材词，同样长词优先。
  static final List<String> ingredientsByLength = <String>[...ingredients]
    ..sort((a, b) => b.length.compareTo(a.length));

  /// 一行里规范词的**加权命中分**（给 OCR 错版择优当语义证据）。
  ///
  /// 为什么按词长加权而不是数个数：词表里同时有「小米」和「小米辣」。
  /// 只数个数时，「小米鎌1根」命中「小米」得 1 分，「小米辣1根」命中
  /// 「小米辣」也得 1 分 —— 泛词把长词抵消了，等于白加。三字专名比两字
  /// 泛词信息量大得多，所以命中一个 n 字词给 n 分。
  ///
  /// 命中过的词会从待匹配串里挖掉，避免「白糖」和「糖」重复计分。
  /// 单字词不参与（噪声太大）；整行十几字、几百次 contains 是毫秒级，
  /// 不会影响整理速度。
  static int semanticScore(String line) {
    if (line.isEmpty) return 0;
    var rest = line;
    var score = 0;
    for (final w in allWords) {
      if (w.length < 2) continue;
      if (rest.contains(w)) {
        score += w.length;
        rest = rest.replaceAll(w, ' ');
      }
    }
    return score;
  }

  /// 整词精确替换。不做模糊匹配，宁可留着错字也不猜。
  static String correct(String line) {
    var out = line;
    for (final e in corrections.entries) {
      if (out.contains(e.key)) out = out.replaceAll(e.key, e.value);
    }
    return out;
  }

  /// 对整份字幕做词级纠正。[hits] 收改动说明，写进运行日志便于核对。
  static List<String> normalizeLines(
    List<String> lines, {
    List<String>? hits,
  }) {
    var count = 0;
    final out = <String>[];
    for (final l in lines) {
      final fixed = correct(l);
      if (fixed != l) {
        count++;
        hits?.add('「$l」→「$fixed」');
      }
      out.add(fixed);
    }
    if (count > 0) {
      hits?.insert(0, '厨房词表纠正 $count 行');
    }
    return out;
  }

  /// 词表里有没有这个词（供标题打分、测试用）。
  static bool isKnown(String word) => allWords.contains(word);
}
