//
// 【为什么要有这一层】
// 用户问「是不是缺一个数据库」时发现：库其实已经有三份，只是散在各处、互不通气：
//   · ingredient_scan.dart   182 个食材/调料词，只用来报「可能漏了某样料」
//   · subtitle_clean.dart    数字+单位的形近字表（8/A/p/元 → g）
//   · asr_fixer.dart         语音同音字表
// 而真正决定 OCR 错版谁赢的 subtitle_fuse._score / SubtitleClean.score，
// 只看「汉字数 / 数字+单位 / 乱码符号」，**完全没用上「这个词是不是真实的
// 调料」这个最强证据**。于是「小米鎌1根」和「小米辣1根」平票时只能靠字频猜，
// 错版被选中的事就发生了。
//
// 所以不是从零建库，是把三份碎片收成一处，让择优、纠错、扫料共用同一张表。
//
// 【边界：只收封闭集合，不枚举菜名】
// 调料 / 食材 / 单位 / 烹饪动作 / 火候是封闭集合，几百词、稳定，覆盖绝大多数
// OCR 错字（错的是「白糖→白糠」「老抽→老迪」这类常用字，不是生僻菜名）。
// 菜名是开放集合，每个博主都能造新名，枚举永远追不上 —— 那部分交给
// TitleFixer 的话题标签与构词规则，不放进这里。
//
// 【纠错必须保守】
// 只做「整词精确替换」，不做模糊匹配、不按编辑距离猜。理由：把「虾皮」
