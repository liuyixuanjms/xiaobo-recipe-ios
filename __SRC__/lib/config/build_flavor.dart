/// 构建变体开关（v1.33）
///
/// 为什么要有这个东西：同一个 App 要出两个包，内容处理的算法完全一样，
/// 只有「素材从哪来」这一环不同。
///
///   · 自用版（默认）：保留「贴链接自动读」，行为和 v1.32 一模一样。
///     自己侧载、自己用，不上架。
///
///   · 上架版（`--dart-define=INTERNAL=false`）：只有「从相册/文件导入」入口。
///     所有解析第三方链接的代码在这条分支下永远不会被调用，
///     AOT 编译会把它当死代码剔除掉，产物里不留痕迹。
///
/// 默认值是 true —— 刻意选的。用户日常就是自己用，不给他每次构建都加参数的负担；
/// 出上架包时显式写 `--dart-define=INTERNAL=false`，反而更容易记住自己在做发布。
library build_flavor;

/// true = 自用版（含链接入口）；false = 上架版（仅本地素材）
const bool kInternal = bool.fromEnvironment('INTERNAL', defaultValue: true);

/// 给日志和设置页显示用的名字
String get flavorName => kInternal ? '自用版' : '上架版';

/// App 在界面里自称的名字（v1.34，v1.39 对调）
///
/// 两个包可以同时装在一台手机上（包名不同），如果界面里都写「小波菜谱」，
/// 用户切来切去会分不清自己在看哪一个 —— 尤其是要对比「贴链接」和「相册导入」
/// 两种入口的时候。所以名字必须跟着变体走。
///
/// v1.39 为什么对调：上架版改名叫「小波菜谱」（它才是对外那个正主），
/// 自用版加后缀叫「小波菜谱自用」。之前反着来的时候，上架版那个名字
/// 带着「上架版」三个字，摆在桌面上怎么看都像个测试包。
///
/// 注意：这只是界面文字。桌面图标下的名字由 build.gradle 的 resValue
/// 按 APP_VARIANT 注入，两处必须一起改，否则会出现「桌面叫一个名、
/// 打开后标题栏叫另一个名」的错位。
const String kAppName = kInternal ? '小波菜谱自用' : '小波菜谱';
