// 干活时的进度换算（v1.43）。
//
// 为什么单独抽出来：进度条准不准，用户一眼就能看出来。做成纯函数才能写测试，
// 不然改一个字就得重新装包、贴链接、等两分钟才知道有没有算错。
//
// 【v1.43 按真机日志重算】
// 旧注释写「听语音 Paraformer 1~5 秒」，是开发机短样片的数字，跟真机差一个数量级。
// 2026-11-15 导出的日志里，三次运行的实测（秒）：
//               解析   下载   抽帧   OCR   听口播   整理+出图
//   51 秒视频    4.4    0    10.5   4.1    37.1      2.4
//   324 秒视频  11.2    0    24.3   9.8   240(超时)  1.4
//   427 秒视频   4.4   34.4   33.0  14.5   240(超时)  1.5
// 听口播那一步已经从必经路径上拿掉（字幕够密就不听，见 asr_policy.dart），
// 所以里程碑按「解析 → 下载 → 抽帧 → OCR → 整理 → 配图」重新分。
//
// 另一个体验修正：以前抽帧和 OCR 共用一个进度值，最长的十几到几十秒里
// 进度条纹丝不动。现在两者各占一个里程碑，并在 ocrFrames 前回调一次。
class StageProgress {
  /// 阶段关键字 → 累计进度。文案里命中即取，多个命中取最大。
  static const List<List<Object>> milestones = [
    ['正在解析链接', 0.02],
    ['正在解析小红书', 0.02],
    ['正在读这条笔记', 0.05],
    ['正在直接读作品页', 0.05],
    ['正在打开作品页', 0.10],
    ['正在用浏览器打开笔记', 0.10],
    ['正在取作品里的图', 0.12],
    ['正在取笔记里的图', 0.12],
    ['正在下载视频', 0.18],
    ['正在抽帧读字幕', 0.38],
    ['正在读图片上的文字', 0.62],
    ['正在听视频里说了什么', 0.70],
    ['正在整理成菜谱', 0.82],
    ['本地正在切步骤', 0.84],
    ['本地正在核对用料', 0.90],
    ['正在给', 0.96],
  ];

  /// 本地整理四步（规划 / 切步骤 / 核对 / 收尾）各自的进度。
  ///
  /// 起点必须 ≥ 整理阶段的 0.82，否则进度条会往回退。
  static const List<double> aiSteps = [0.84, 0.88, 0.92, 0.95];

  /// 按文案查进度；查不到返回 null（调用方保持原进度不动）。
  static double? lookup(String label) {
    double? best;
    for (final m in milestones) {
      final key = m[0] as String;
      if (!label.contains(key)) continue;
      final p = m[1] as double;
      if (best == null || p > best) best = p;
    }
    return best;
  }

  /// 第 [step] 步（从 1 开始）的进度。
  static double aiStep(int step) {
    final i = (step - 1).clamp(0, aiSteps.length - 1);
    return aiSteps[i];
  }
}
