/// 把语音识别出来的同音错字改回食材名。
///
/// 为什么需要：哪怕换了准确率最高的引擎，中文听写对「食材名」仍然最容易错，
/// 因为食材名大多是单字或双字冷门词，语言模型没有上下文可依靠。
/// 实测 Paraformer 的残余错误就集中在这里：
///   「尖青椒」→「煎青椒」、「不用去根」→「不用去跟」
///
/// 这类错字有两个后果，都很要命：
/// 1. AI 看到「煎青椒」会当成一道菜名，不把它列进用料；用户上次漏掉尖青椒就是这么来的。
/// 2. 本地漏料扫描拿原文去比对食材表，「离」永远匹配不上「梨」。
///
/// 所以这里做一层**保守**替换：只改「几乎不可能有别的意思」的组合，
/// 宁可漏改，也绝不把「离开」改成「梨开」这种。
class AsrFixer {
  AsrFixer._();

  /// 每条规则：正则 → 替换内容（可带 $1 分组）+ 人话说明（写进日志，方便核对）
  static final List<_Rule> _rules = <_Rule>[
    // ── 梨：单字，最容易被写成同音字，也是用户第一次投诉漏掉的东西 ──
    _Rule(RegExp(r'个离'), '个梨', '个离→个梨'),
    _Rule(RegExp(r'一离(?!开)'), '一梨', '一离→一梨'),
    _Rule(RegExp(r'两离(?!开)'), '两梨', '两离→两梨'),
    _Rule(RegExp(r'半离(?!开)'), '半梨', '半离→半梨'),
    _Rule(RegExp(r'离(切|片|块|子)'), r'梨$1', '离切片→梨切片'),
    _Rule(RegExp(r'(放|加|下|来)(一)?离(?!开)'), r'$1$2梨', '放个离→放个梨'),

    // ── 尖青椒：三个字，前两个字最常错 ──
    _Rule(RegExp(r'[筋煎金今紧]青椒'), '尖青椒', '筋/煎/金青椒→尖青椒'),

    // ── 去根 / 带皮 / 整根 这类处理方式 ──
    _Rule(RegExp(r'去跟'), '去根', '去跟→去根'),
    _Rule(RegExp(r'整跟'), '整根', '整跟→整根'),

    // ── 香菜 ──
    _Rule(RegExp(r'香才'), '香菜', '香才→香菜'),
    _Rule(RegExp(r'相菜'), '香菜', '相菜→香菜'),
    _Rule(RegExp(r'香采'), '香菜', '香采→香菜'),

    // ── 苹果 ──
    _Rule(RegExp(r'平果'), '苹果', '平果→苹果'),
    _Rule(RegExp(r'苹朵'), '苹果', '苹朵→苹果'),

    // ── 调料（这几组在老引擎上几乎每次都错，留着不亏） ──
    _Rule(RegExp(r'生手'), '生抽', '生手→生抽'),
    _Rule(RegExp(r'老曲'), '老抽', '老曲→老抽'),
    _Rule(RegExp(r'好油'), '蚝油', '好油→蚝油'),
    _Rule(RegExp(r'耗油'), '蚝油', '耗油→蚝油'),

    // ── 厨房场景高频 OCR 错字 ──
    //
    // 全部来自 2026-11-12 19:24 那份真实日志里的字幕行。
    // 这些字单独看各有各的意思，只有**合起来**才几乎不可能是别的词，
    // 所以一律按词组替换，不做单字替换 —— 宁可漏改，不能把正常话改坏。
    _Rule(RegExp(r'虾抢'), '虾枪', '虾抢→虾枪'),
    _Rule(RegExp(r'虾眼晴'), '虾眼睛', '虾眼晴→虾眼睛'),
    _Rule(RegExp(r'([一二三四五六七八九])关书'), r'$1关节', '关书→关节'),
    _Rule(RegExp(r'剪导'), '剪子', '剪导→剪子'),
    _Rule(RegExp(r'剪律'), '剪掉', '剪律→剪掉'),
    _Rule(RegExp(r'虹虾'), '大虾', '虹虾→大虾'),
    _Rule(RegExp(r'自糖'), '白糖', '自糖→白糖'),
    _Rule(RegExp(r'但抽'), '生抽', '但抽→生抽'),
    _Rule(RegExp(r'簿盐'), '薄盐', '簿盐→薄盐'),
    _Rule(RegExp(r'請水'), '清水', '請水→清水'),
    _Rule(RegExp(r'客易'), '容易', '客易→容易'),
    _Rule(RegExp(r'比校'), '比较', '比校→比较'),
    _Rule(RegExp(r'快連'), '快速', '快連→快速'),
    _Rule(RegExp(r'兰部分'), '一部分', '兰部分→一部分'),
    _Rule(RegExp(r'橄敢榄油'), '橄榄油', '橄敢榄油→橄榄油'),
    _Rule(RegExp(r'许杭檬'), '柠檬', '许杭檬→柠檬'),
    _Rule(RegExp(r'转團'), '转圈', '转團→转圈'),
    _Rule(RegExp(r'提拌|挺拌'), '搅拌', '提拌/挺拌→搅拌'),
    // 「小米辣」在这段视频里被读成三种样子
    _Rule(RegExp(r'小米?鎌'), '小米辣', '小米鎌→小米辣'),
    _Rule(RegExp(r'小来辣'), '小米辣', '小来辣→小米辣'),
    // 用量写法：一平勺被读成「一平勾」
    _Rule(RegExp(r'一平勾'), '一平勺', '一平勾→一平勺'),
    // 「处理好的虾」被读成「0理好的舒」
    _Rule(RegExp(r'0理'), '处理', '0理→处理'),
    _Rule(RegExp(r'好的舒'), '好的虾', '好的舒→好的虾'),
    // 剩下这几条都是「整句读下来才能确定」的常见错，单独一个字绝不改
    _Rule(RegExp(r'个尖比较'), '个头比较', '个尖→个头'),
    _Rule(RegExp(r'把網'), '把锅', '把網→把锅'),
    _Rule(RegExp(r'邸酱'), '麻酱', '邸酱→麻酱'),
    _Rule(RegExp(r'香朝'), '香锅', '香朝→香锅'),
    _Rule(RegExp(r'翻炒几市'), '翻炒几下', '几市→几下'),
    _Rule(RegExp(r'完全收无'), '完全收干', '收无→收干'),
    // 「腌制」被读成「脆制」「淹制」（这份 45 秒视频里连错两处）
    _Rule(RegExp(r'脆制|淹制'), '腌制', '脆制/淹制→腌制'),
    // ── v1.29：187 秒茄汁大虾那份日志里，同一句「生抽40g(薄盐,正常咸度的…」
    // 被读了 5 个版本，其中「薄盐」「正常咸度」这两个词被读成六种样子。
    // 这两处错得特别显眼（「薄益」「薄虔」「工常成度」），且不可能有别的意思。
    _Rule(RegExp(r'薄[益虔簿]'), '薄盐', '薄益/薄虔→薄盐'),
    _Rule(RegExp(r'[工正][常念]?成度'), '正常咸度', '工常成度/正念成度→正常咸度'),
    // 「大虾」的「大」少一横 → 「次虾」
    _Rule(RegExp(r'次虾'), '大虾', '次虾→大虾'),
    // 「虾本身有咸味」→「虾衣身」
    _Rule(RegExp(r'虾衣身'), '虾本身', '虾衣身→虾本身'),
    // 日文长音符混进来：「可以刷均匀ー点」
    _Rule(RegExp(r'ー点'), '一点', 'ー点→一点'),
    // 繁体「鍋」被 OCR 混着读出来，统一成简体（「锅」在句子里不会有歧义）
    _Rule(RegExp(r'鍋'), '锅', '鍋→锅'),
    // 「網」多半是「网」，只有下面这几种组合才是「锅」
    _Rule(RegExp(r'網(中|里|盖|底|边)'), r'锅$1', '網→锅'),
  ];

  /// 返回改好的文本。
  ///
  /// [hits] 不为空时会写入「改了哪几处」，调用方拿去打日志 ——
  /// 用错了规则（把正常词改坏）能立刻从日志里看出来，不用等到菜谱出错才发现。
  static String fix(String text, {List<String>? hits}) {
    if (text.trim().isEmpty) return text;
    var s = text;
    for (final r in _rules) {
      final before = s;
      // 必须用 replaceAllMapped：Dart 的 replaceAll **不认** $1 这种分组引用，
      // 直接传 '梨$1' 会把 "$1" 原样写进文本（这个坑踩过一次）。
      s = s.replaceAllMapped(r.pattern, (match) {
        var rep = r.replace;
        for (var i = 1; i <= match.groupCount; i++) {
          rep = rep.replaceAll('\$$i', match.group(i) ?? '');
        }
        return rep;
      });
      if (s != before && hits != null) hits.add(r.note);
    }
    return s;
  }
}

class _Rule {
  const _Rule(this.pattern, this.replace, this.note);

  final RegExp pattern;
  final String replace;
  final String note;
}
